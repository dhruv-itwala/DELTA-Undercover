// Anti-repetition engine: keeps track of recent word pairs in sessionStorage
const RECENT_WORDS_STORAGE_KEY = 'undercover_recent_words_v2';

function getRecentWords() {
  try {
    const raw = sessionStorage.getItem(RECENT_WORDS_STORAGE_KEY);
    return raw ? JSON.parse(raw) : [];
  } catch {
    return [];
  }
}

function recordUsedWord(civilianWord) {
  try {
    const recent = getRecentWords();
    recent.push(civilianWord.toLowerCase());
    // Keep last 60 words to prevent repeated encounters in games
    if (recent.length > 60) {
      recent.shift();
    }
    sessionStorage.setItem(RECENT_WORDS_STORAGE_KEY, JSON.stringify(recent));
  } catch {
    // Session storage not available
  }
}

export function getRandomWordPair(selectedPackId = 'all') {
  let pool = [];
  if (selectedPackId === 'all') {
    pool = WORD_PACKS.flatMap(p => p.pairs);
  } else {
    const pack = WORD_PACKS.find(p => p.id === selectedPackId);
    pool = pack ? pack.pairs : WORD_PACKS[0].pairs;
  }

  const recent = getRecentWords();
  // Filter out recently used pairs
  let freshPool = pool.filter(p => 
    !recent.includes(p.civilian.toLowerCase()) && 
    !recent.includes(p.imposter.toLowerCase())
  );

  // If entire pool was exhausted, reset memory
  if (freshPool.length === 0) {
    freshPool = pool;
    try {
      sessionStorage.removeItem(RECENT_WORDS_STORAGE_KEY);
    } catch {
      // Ignore
    }
  }

  const randomIndex = Math.floor(Math.random() * freshPool.length);
  const selectedPair = freshPool[randomIndex];

  // Randomly assign which is civilian vs imposter so order doesn't leak clues
  const flip = Math.random() > 0.5;
  const result = {
    civilian: flip ? selectedPair.civilian : selectedPair.imposter,
    imposter: flip ? selectedPair.imposter : selectedPair.civilian
  };

  recordUsedWord(result.civilian);
  return result;
}
